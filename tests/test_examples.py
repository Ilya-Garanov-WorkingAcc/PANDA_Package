"""Examples from examples/ run and print what is expected (those that need no MD files)."""

import os
import subprocess
import sys
from pathlib import Path

import pytest

from panda_md.cli.config import load_config

EXAMPLES = Path(__file__).parents[1] / "examples"


def run_example(name: str, *arguments: str) -> str:
    completed = subprocess.run(
        [sys.executable, "-X", "utf8", str(EXAMPLES / name), *arguments],
        capture_output=True,
        encoding="utf-8",
        check=False,
        env={**os.environ, "MPLBACKEND": "Agg"},
    )
    assert completed.returncode == 0, completed.stderr
    return completed.stdout


def test_synthetic_fit_recovers_the_angle() -> None:
    out = run_example("01_synthetic_fit.py")
    fitted = float(out.split("fitted ")[1].split("°")[0])
    assert fitted == pytest.approx(120.0, abs=1.5)


def test_saved_profiles_give_the_graphite_angle(tmp_path: Path) -> None:
    arguments = ("--output", str(tmp_path)) if _has_matplotlib() else ()
    out = run_example("03_saved_profiles.py", *arguments)
    assert "slit/roll: 8 block(s)" in out
    if arguments:
        assert (tmp_path / "graphite_water.png").stat().st_size > 0


def test_stability_diagram_example(tmp_path: Path) -> None:
    arguments = ("--output", str(tmp_path)) if _has_matplotlib() else ()
    out = run_example("04_stability_diagram.py", *arguments)
    assert "slit: shapes on the diagram" in out and "square: shapes on the diagram" in out


def test_custom_shape_is_fitted_and_wins_the_comparison() -> None:
    out = run_example("05_custom_shape.py")
    comparison = out.split("shape comparison")[1].splitlines()
    assert comparison[1].split()[0] == "bottom_film"


def test_example_settings_file_is_valid() -> None:
    config = load_config(EXAMPLES / "panda.toml")
    assert config.fit is not None and config.fit.shape == "roll"
    assert config.profile.topology == EXAMPLES / "system.tpr"


def _has_matplotlib() -> bool:
    try:
        import matplotlib  # noqa: F401
    except ImportError:
        return False
    return True


@pytest.mark.parametrize(
    ("notebook_name", "builder_name"),
    [("test_panda.ipynb", "build_test_notebook.py"), ("demo.ipynb", "build_demo_notebook.py")],
)
def test_notebooks_compile_and_match_their_builders(notebook_name: str, builder_name: str) -> None:
    """The notebooks are generated by their builder scripts; every code cell is valid Python."""
    import importlib.util
    import json

    notebook = json.loads((EXAMPLES / notebook_name).read_text(encoding="utf-8"))
    sources = ["".join(cell["source"]) for cell in notebook["cells"]]
    for cell, source in zip(notebook["cells"], sources, strict=True):
        if cell["cell_type"] == "code":
            compile(source, notebook_name, "exec")
    pytest.importorskip("nbformat")  # the notebook builder is needed only for the comparison with it
    spec = importlib.util.spec_from_file_location(builder_name.removesuffix(".py"), EXAMPLES / builder_name)
    assert spec is not None and spec.loader is not None
    builder = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(builder)
    assert sources == [source for _, source in builder.CELLS]
