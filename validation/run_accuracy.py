"""Accuracy of the method on synthetic data: figures and tables for the documentation and the paper.

Run from the repository root (needs panda-md[plot]):
    uv run python validation/run_accuracy.py
Output: validation/figures/*.png and validation/REPORT.md. The tables are rebuilt on every run; the conclusions are
written by hand in validation/README.md and must be checked against the tables after a rerun. Takes about a minute.
"""

import time
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # no window: files only

import matplotlib.pyplot as plt

from panda_md import Frame, SlitPore
from panda_md.analysis.accuracy import AccuracyCase, AccuracyStudy, accuracy_study
from panda_md.plotting import plot_accuracy

HERE = Path(__file__).parent
FIGURES = HERE / "figures"
REPORT = HERE / "REPORT.md"
DENSITY_BULK = 30.0
SEEDS = range(10)
PORE = SlitPore(width_nm=8.0, length_nm=16.0)
TRUTHS = {
    "roll": {"theta": 120.0, "delta": 0.03, "phi": 0.4},
    "droplet": {"theta": 130.0, "delta": 0.03, "phi": 0.05},
    "worm": {"theta": 130.0, "delta": 0.03, "phi": 0.1},
}
NOISE_LEVELS = (0.0025, 0.005, 0.01, 0.02)
BIN_COUNTS = (50, 100, 200, 400)
ANGLES = (100.0, 120.0, 140.0, 160.0, 170.0, 175.0)
BASE_NOISE = 0.005
WALL_ERROR = 0.05  # error of the wall positions: 5 % of the slit width


def noise_study(shape: str) -> AccuracyStudy:
    cases = {
        f"{100 * noise:g}": (100 * noise, AccuracyCase(truth=TRUTHS[shape], noise_std=noise)) for noise in NOISE_LEVELS
    }
    return accuracy_study(
        PORE.interface(shape), "noise, % of ρ_bulk per bin", cases, density_bulk_per_nm3=DENSITY_BULK, seeds=SEEDS
    )


def bins_study(shape: str) -> AccuracyStudy:
    cases = {
        f"{bins}": (float(bins), AccuracyCase(truth=TRUTHS[shape], noise_std=BASE_NOISE, bin_count=bins))
        for bins in BIN_COUNTS
    }
    return accuracy_study(PORE.interface(shape), "bins", cases, density_bulk_per_nm3=DENSITY_BULK, seeds=SEEDS)


def angle_study(shape: str) -> AccuracyStudy:
    cases = {}
    for angle in ANGLES:
        truth = {**TRUTHS[shape], "theta": angle}
        if not PORE.interface(shape).is_feasible(**truth):
            continue
        cases[f"{angle:g}"] = (angle, AccuracyCase(truth=truth, noise_std=BASE_NOISE))
    return accuracy_study(PORE.interface(shape), "θ, °", cases, density_bulk_per_nm3=DENSITY_BULK, seeds=SEEDS)


def centering_study(shape: str) -> AccuracyStudy:
    truth = TRUTHS[shape]
    cases = {
        "pore": (0.0, AccuracyCase(truth=truth, noise_std=BASE_NOISE, offset=WALL_ERROR)),
        "pore + shift": (
            1.0,
            AccuracyCase(truth=truth, noise_std=BASE_NOISE, offset=WALL_ERROR, optimize=("theta", "delta", "shift")),
        ),
        "liquid, known δ": (
            2.0,
            AccuracyCase(
                truth=truth,
                noise_std=BASE_NOISE,
                offset=WALL_ERROR,
                frame=Frame.LIQUID,
                optimize=("theta",),
                fixed={"delta": truth["delta"]},
            ),
        ),
    }
    return accuracy_study(PORE.interface(shape), "centering on", cases, density_bulk_per_nm3=DENSITY_BULK, seeds=SEEDS)


def describe(truth: dict[str, float], study_key: str) -> str:
    """True parameters for the section title; θ varies in the angle study and is left out there."""
    shown = {name: value for name, value in truth.items() if not (study_key == "angle" and name == "theta")}
    return ", ".join(f"{name} = {value:g}" for name, value in shown.items())


def save_figure(study: AccuracyStudy, name: str) -> str:
    figure, axes = plt.subplots(figsize=(5.0, 3.6))
    plot_accuracy(study, axes)
    figure.tight_layout()
    path = FIGURES / f"{name}.png"
    figure.savefig(path, dpi=120)
    plt.close(figure)
    return path.name


def main() -> None:
    FIGURES.mkdir(exist_ok=True)
    started = time.perf_counter()
    sections = [
        "# Accuracy of the method on synthetic data\n",
        f"Generated by `validation/run_accuracy.py`. Slit {PORE.width_nm:g} × {PORE.length_nm:g} nm, ρ_bulk = "
        f"{DENSITY_BULK:g} nm⁻³, {len(SEEDS)} noise seeds per point, fit with the default settings (θ and δ free, "
        f"φ from ∫ρ). The noise is given for 200 bins and scaled as √(bins / 200). Δθ = recovered − true.\n",
    ]
    studies = [
        ("Noise", "noise", noise_study, ("roll", "droplet", "worm")),
        ("Number of bins (noise 0.5 % at 200 bins)", "bins", bins_study, ("roll", "droplet")),
        ("Angle (noise 0.5 %): accuracy near 180°", "angle", angle_study, ("roll", "droplet", "worm")),
        ("Centering with the walls off by 5 % of H", "centering", centering_study, ("roll", "droplet")),
    ]
    for title, key, build, shapes in studies:
        sections.append(f"\n## {title}\n")
        for shape in shapes:
            study = build(shape)
            figure = save_figure(study, f"{key}_{shape}")
            sections.append(
                f"\n### {shape} ({describe(TRUTHS[shape], key)})\n\n{study.table()}\n\n![{shape}](figures/{figure})\n"
            )
            print(f"{key}/{shape}: {time.perf_counter() - started:.0f} s", flush=True)
    REPORT.write_text("".join(sections))
    print(f"written: {REPORT}")


if __name__ == "__main__":
    main()
